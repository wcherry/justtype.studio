#!/usr/bin/env bash
#
# Resolves the Apple Developer team and writes ios/Signing.xcconfig.
#
# The team id is a property of whoever is building, not of the project, so it
# lives in scripts/.env (gitignored) rather than in ios/project.yml. Keeping it
# out of the repo means a fork or a second developer does not inherit someone
# else's signing identity, and CI can supply its own through the environment.
#
# An xcconfig rather than a plain variable, because three things need the team
# and only one of them is a shell: xcodebuild from these scripts, and Xcode
# itself when the project is opened by hand. project.yml points both build
# configurations at this file, so all of them read the same value.
#
# The file is always written, even with no team set — xcodegen refuses to
# generate a project whose configFiles path does not exist.
#
#   scripts/ios_signing.sh      # write the xcconfig and report the team
#
# Sourced by run_simulator.sh and deploy_testflight.sh for the same helpers.

# Only assigned when unset: the sourcing script has already declared these
# readonly, and assigning to a readonly variable is an error even with the same
# value.
if [[ -z "${REPO_ROOT:-}" ]]; then
  REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fi
if [[ -z "${IOS_DIR:-}" ]]; then
  IOS_DIR="$REPO_ROOT/ios"
fi
SIGNING_XCCONFIG="$IOS_DIR/Signing.xcconfig"

# The sourcing scripts define these; standalone runs need their own.
if ! declare -F die >/dev/null 2>&1; then
  log()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
  warn() { printf '\033[1;33mwarning:\033[0m %s\n' "$*" >&2; }
  die()  { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }
fi

# DEVELOPMENT_TEAM from the environment wins; otherwise scripts/.env supplies
# it. ASC_TEAM_ID is accepted as an alias, since the App Store Connect
# credentials next to it are all ASC_-prefixed.
ios_load_env() {
  # Captured before the file is sourced: `set -a; source` would otherwise
  # overwrite an explicit environment value with the file's, which is backwards
  # and would leave CI unable to override a stray checked-out .env.
  local from_env="${DEVELOPMENT_TEAM:-${ASC_TEAM_ID:-}}"
  if [[ -f "$REPO_ROOT/scripts/.env" ]]; then
    set -a
    # shellcheck disable=SC1091  # gitignored, per-developer, not in the repo
    source "$REPO_ROOT/scripts/.env"
    set +a
  fi
  DEVELOPMENT_TEAM="${from_env:-${DEVELOPMENT_TEAM:-${ASC_TEAM_ID:-}}}"
}

ios_write_signing_xcconfig() {
  ios_load_env
  mkdir -p "$IOS_DIR"
  {
    echo "// Generated by scripts/ios_signing.sh. Do not edit, do not commit."
    echo "// The value comes from DEVELOPMENT_TEAM in scripts/.env."
    if [[ -n "$DEVELOPMENT_TEAM" ]]; then
      echo "DEVELOPMENT_TEAM = $DEVELOPMENT_TEAM"
    else
      echo "// No team set. Simulator builds work without one; device builds,"
      echo "// archives and uploads do not. Copy scripts/.env.example to"
      echo "// scripts/.env and set DEVELOPMENT_TEAM."
    fi
  } > "$SIGNING_XCCONFIG"
}

# For the paths that genuinely cannot proceed without a team. The second
# argument is a closing hint, since what to do instead differs by caller.
ios_require_team() {
  local what="${1:-this build}" hint="${2:-}"
  [[ -n "${DEVELOPMENT_TEAM:-}" ]] || die "no Apple Developer team set, and $what has to be code-signed.
  Copy scripts/.env.example to scripts/.env and set DEVELOPMENT_TEAM to your
  Team ID (Apple Developer > Membership, or Xcode > Settings > Accounts).${hint:+
  $hint}"
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
  set -euo pipefail
  ios_write_signing_xcconfig
  if [[ -n "$DEVELOPMENT_TEAM" ]]; then
    log "Signing team: $DEVELOPMENT_TEAM -> ${SIGNING_XCCONFIG#"$REPO_ROOT"/}"
  else
    warn "no DEVELOPMENT_TEAM set — wrote ${SIGNING_XCCONFIG#"$REPO_ROOT"/} without one."
    warn "Simulator builds will work; device builds and archives will not."
  fi
fi
